const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const esbuild = require('esbuild');

const projectRoot = path.join(__dirname, '..');
const publicDir = path.join(projectRoot, 'public');
const entryPoint = 'src/client/listings/main.js';
const outfile = 'public/assets/listings.js';
const COMPRESSIBLE_EXTENSIONS = new Set(['.html', '.css', '.js', '.svg']);

function collectFiles(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      collectFiles(fullPath, files);
    } else if (entry.isFile()) {
      files.push(fullPath);
    }
  }
  return files;
}

function precompressPublicAssets(targetDir = publicDir) {
  const files = collectFiles(targetDir);
  const activeSidecars = new Set();

  for (const filePath of files) {
    const ext = path.extname(filePath).toLowerCase();
    if (ext === '.br' || ext === '.gz') continue;
    if (!COMPRESSIBLE_EXTENSIONS.has(ext)) continue;

    const raw = fs.readFileSync(filePath);
    const brPath = `${filePath}.br`;
    const gzPath = `${filePath}.gz`;
    activeSidecars.add(brPath);
    activeSidecars.add(gzPath);

    const br = zlib.brotliCompressSync(raw, {
      params: {
        [zlib.constants.BROTLI_PARAM_MODE]: zlib.constants.BROTLI_MODE_TEXT,
        [zlib.constants.BROTLI_PARAM_QUALITY]: 11,
      },
    });
    if (!fs.existsSync(brPath) || !fs.readFileSync(brPath).equals(br)) {
      fs.writeFileSync(brPath, br);
    }

    const gz = zlib.gzipSync(raw, { level: 9 });
    if (!fs.existsSync(gzPath) || !fs.readFileSync(gzPath).equals(gz)) {
      fs.writeFileSync(gzPath, gz);
    }
  }

  for (const filePath of files) {
    if ((filePath.endsWith('.br') || filePath.endsWith('.gz')) && !activeSidecars.has(filePath)) {
      fs.unlinkSync(filePath);
    }
  }
}

async function buildListings({ write = true, precompress = write } = {}) {
  const result = await esbuild.build({
    absWorkingDir: projectRoot,
    entryPoints: [entryPoint],
    outfile,
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: ['es2020'],
    minify: true,
    write,
    legalComments: 'none',
    define: { __RPF_BROWSER_BUNDLE__: 'true' },
    banner: {
      js: '// Generated by scripts/build-listings.js. Edit src/client/listings/* instead.',
    },
  });

  if (write && precompress) {
    precompressPublicAssets(publicDir);
  }

  return result;
}

if (require.main === module) {
  buildListings().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}

module.exports = {
  buildListings,
  precompressPublicAssets,
};
