const path = require('node:path');
const esbuild = require('esbuild');

const projectRoot = path.join(__dirname, '..');
const entryPoint = 'src/client/listings/main.js';
const outfile = 'public/assets/listings.js';

async function main() {
  await esbuild.build({
    absWorkingDir: projectRoot,
    entryPoints: [entryPoint],
    outfile,
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: ['es2020'],
    minify: false,
    legalComments: 'none',
    define: { __RPF_BROWSER_BUNDLE__: 'true' },
    banner: {
      js: '// Generated by scripts/build-listings.js. Edit src/client/listings/* instead.',
    },
  });
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
